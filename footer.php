    <script>
    document.addEventListener('DOMContentLoaded', function() {
      const userMenuTrigger = document.querySelector('[data-user-menu-trigger]');
      const userMenuDropdown = document.querySelector('[data-user-menu-dropdown]');
      
      if (userMenuTrigger && userMenuDropdown) {
        let isOpen = false;
        
        function toggleMenu() {
          isOpen = !isOpen;
          userMenuDropdown.classList.toggle('hidden', !isOpen);
        }
        
        function closeMenu() {
          isOpen = false;
          userMenuDropdown.classList.add('hidden');
        }
        
        userMenuTrigger.addEventListener('click', function(e) {
          e.preventDefault();
          e.stopPropagation();
          toggleMenu();
        });
        
        // Close menu when clicking outside
        document.addEventListener('click', function(e) {
          if (!userMenuTrigger.contains(e.target) && !userMenuDropdown.contains(e.target)) {
            closeMenu();
          }
        });
        
        // Close menu when pressing Escape
        document.addEventListener('keydown', function(e) {
          if (e.key === 'Escape') {
            closeMenu();
          }
        });
        
        // Close menu when window is resized (mobile responsiveness)
        window.addEventListener('resize', function() {
          if (window.innerWidth < 1024) {
            closeMenu();
          }
        });
      }
    });
    </script>
